#!/usr/bin/env bash
# Refresh the "Live jobs" section of paper/revision/EXPERIMENT_STATUS.md from squeue, plus result counts of the
# other-tokenizer campaign. Only the text between the LIVE-START / LIVE-END markers is rewritten.
#   bash scripts/experiment_status.sh
set -euo pipefail
cd "$(dirname "$0")/.."
F=paper/revision/EXPERIMENT_STATUS.md
TMP=$(mktemp)
{
  echo "<!-- LIVE-START (generated by scripts/experiment_status.sh, do not edit by hand) -->"
  echo "Updated: $(date '+%Y-%m-%d %H:%M')"
  echo
  echo "| Job group | Partition | State | Jobs |"
  echo "|---|---|---|---|"
  # NAU rebuttal job names only; other projects' jobs (item memory, BONSAI, ...) are counted below, not listed
  NAU_RE='^(vsb_|otk_|miarm_|miaotk_|rmgrid|rank_|nau0|sens_scrub|archive_ckpts|bench_sep|sepfast|valsens|rmsplit)'
  squeue -u "$USER" -h -o '%j|%P|%T' | grep -v '^bash|' | grep -E "${NAU_RE}" \
    | awk -F'|' '{g=$1; sub(/_(big|any)_[0-9]+$/,"",g); print g"|"$2"|"$3}' | sort | uniq -c \
    | awk '{n=$1; $1=""; sub(/^ /,""); split($0,a,"|"); printf "| %s | %s | %s | %d |\n", a[1], a[2], a[3], n}' || true
  [ -z "$(squeue -u "$USER" -h -o '%j' | grep -E "${NAU_RE}")" ] && echo "| (no NAU jobs queued or running) | | | 0 |"
  echo
  echo "Jobs of other projects in the queue (not tracked here): $(squeue -u "$USER" -h -o '%j' | grep -v '^bash$' | grep -v -c -E "${NAU_RE}")"
  echo
  echo "Other-tokenizer results on disk (runs with cleaned test / cleaned validation evals):"
  echo
  echo "| Tokenizer | Run dirs | Cleaned test | Cleaned val | Target (pinned + grid) |"
  echo "|---|---|---|---|---|"
  for t in rqvae:rqvae:390 letter_letter:letter:390 tracerv3:tracerv3:130; do
    pre=${t%%:*}; rest=${t#*:}; name=${rest%%:*}; tgt=${rest#*:}
    r=$(ls -d logs/unlearn/runs/*_bs1_${pre}_sens_*rmsplit* 2>/dev/null | wc -l)
    n1=$(ls logs/eval/sensitive_scrub/scrub/runs/*_bs1_${pre}_sens_*rmsplit*/eval/csv/version_0/metrics.csv 2>/dev/null | wc -l)
    n2=$(ls logs/eval/sensitive_scrub/scrubval/runs/*_bs1_${pre}_sens_*rmsplit*/eval/csv/version_0/metrics.csv 2>/dev/null | wc -l)
    echo "| ${name} | ${r} | ${n1} | ${n2} | ${tgt} |"
  done
  echo
  echo "Scratch: $(df -h /sc-scratch/sc-scratch-ikim-erase | awk 'NR==2{print $4" free of "$2}')"
  echo "<!-- LIVE-END -->"
} > "${TMP}"
python3 - "$F" "$TMP" <<'EOF'
import re, sys
f, tmp = sys.argv[1], sys.argv[2]
s = open(f).read(); live = open(tmp).read().rstrip("\n")
s2, n = re.subn(r"<!-- LIVE-START.*?<!-- LIVE-END -->", live.replace("\\", "\\\\"), s, flags=re.S)
assert n == 1, "markers not found"
open(f, "w").write(s2)
EOF
rm -f "${TMP}"
echo "updated ${F}"
