"""Decode-time re-ranking vs unlearning on all 15 Beauty cells (extends the testing tree's C8).

Reads logs/rerank15/beauty_<st>_seed<sd>/{poison,nau,clean}/beam50_<spec>/csv/version_0/metrics.csv
(run_rerank15_launch.sh; all evals at beam 50, test split). Per cell the references are the clean
(retrained) model and the poisoned start checkpoint without re-ranking, both at beam 50.

Landed cells: poisoned SH@10 >= clean SH@10 + 0.5 points, decided from those two references only
(before any method is read). Reported over all 15 cells and over landed cells:
  SH@10 (%), Delta^retr_SH = |SH - SH_clean| (points), PGR@10 = (mean SH_p - mean SH) /
  (mean SH_p - mean SH_clean) over the cell set (ratio of means; per-cell PGR is undefined where the
  attack did not land), NDCG@10, tau_P = mean over cells of NDCG / NDCG_clean (%).

    python paper/plotting/rerank15_table.py
Writes paper/revision/tables/appendix_rerank_15cells.tex and paper/revision/rerank_15cells.md.
"""
import csv
import os
import statistics as S

ROOT = "logs/rerank15"
STRATA, SEEDS = ("unpopular", "mid", "popular"), (2, 3, 5, 7, 11)
SPECS = [("none", "no re-ranking"), ("cfr_a3", "re-rank, clean collaborative, $\\alpha=3$"),
         ("cfr_a10", "re-rank, clean collaborative, $\\alpha=10$"),
         ("cfp_a3", "re-rank, poisoned collaborative, $\\alpha=3$"),
         ("cfp_a10", "re-rank, poisoned collaborative, $\\alpha=10$"),
         ("x_a3", "re-rank, content, $\\alpha=3$"), ("x_a10", "re-rank, content, $\\alpha=10$")]
LANDED_PTS = 0.5


def metrics(d):
    f = os.path.join(d, "csv", "version_0", "metrics.csv")
    if not os.path.isfile(f):
        return None
    r = {}
    for row in csv.DictReader(open(f)):
        r.update({k: v for k, v in row.items() if v})
    try:
        return float(r["test/SH@10"]), float(r["test/ndcg@10"])
    except KeyError:
        return None


def main():
    cells = {}
    for st in STRATA:
        for sd in SEEDS:
            base = f"{ROOT}/beauty_{st}_seed{sd}"
            c, p = metrics(f"{base}/clean/beam50_none"), metrics(f"{base}/poison/beam50_none")
            if c and p:
                cells[(st, sd)] = {"base": base, "clean": c, "poison": p,
                                   "landed": 100 * (p[0] - c[0]) >= LANDED_PTS}
    landed = sorted(k for k, v in cells.items() if v["landed"])
    md = ["# Decode-time re-ranking vs unlearning, 15 Beauty cells", "",
          "Generated by `paper/plotting/rerank15_table.py` (beam 50, test split).", "",
          f"Cells with both references: {len(cells)}. Landed (poisoned SH@10 >= clean + {LANDED_PTS} points): "
          f"{len(landed)}: " + ", ".join(f"{st} s{sd}" for st, sd in landed), "",
          "| cell | clean SH@10 (%) | poisoned SH@10 (%) | landed |", "|---|---|---|---|"]
    for (st, sd), v in sorted(cells.items()):
        md.append(f"| {st} s{sd} | {100 * v['clean'][0]:.3f} | {100 * v['poison'][0]:.3f} | {'yes' if v['landed'] else 'no'} |")

    def agg(model, spec, keys):
        ms = [(k, metrics(f"{cells[k]['base']}/{model}/beam50_{spec}")) for k in keys]
        ms = [(k, m) for k, m in ms if m]
        if len(ms) != len(keys) or not keys:
            return None
        sh = [m[0] for _, m in ms]
        shc = [cells[k]["clean"][0] for k, _ in ms]
        shp = [cells[k]["poison"][0] for k, _ in ms]
        nd = [m[1] for _, m in ms]
        tau = [m[1] / cells[k]["clean"][1] for k, m in ms]
        den = S.mean(shp) - S.mean(shc)
        pgr = (S.mean(shp) - S.mean(sh)) / den if abs(den) > 1e-12 else float("nan")
        return (100 * S.mean(sh), 100 * S.mean(abs(a - b) for a, b in zip(sh, shc)), pgr,
                S.mean(nd), 100 * S.mean(tau), len(ms))

    rows = [("poison", s, f"Poisoned, {lab}") for s, lab in SPECS] + \
           [("nau", s, f"NAU, {lab}") for s, lab in SPECS] + [("clean", "none", "Retrained (clean)")]
    allk = sorted(cells)
    res = {(m, s): (agg(m, s, allk), agg(m, s, landed)) for m, s, _ in rows}
    md += ["", "| Model | All: SH@10 (%) | dSH (pts) | PGR@10 | NDCG@10 | tauP (%) | Landed: SH@10 (%) | dSH | PGR@10 | NDCG@10 | tauP |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    f = lambda r: (f"{r[0]:.3f} | {r[1]:.3f} | {r[2]:.2f} | {r[3]:.4f} | {r[4]:.1f}" if r else "-- | -- | -- | -- | --")
    for m, s, lab in rows:
        a, l = res[(m, s)]
        plain = lab.replace("$\\alpha=", "alpha ").replace("$", "")
        md.append(f"| {plain} | {f(a)} | {f(l)} |")

    ft = lambda r: (f"{r[0]:.3f} & {r[1]:.3f} & {r[2]:.2f} & {r[4]:.1f}" if r else "-- & -- & -- & --")
    L = [r"\begin{table}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}", r"\caption{",
         r"Decode-time re-ranking is not a substitute for unlearning (Beauty, TIGER + RQ-KMeans, three targets $\times$ five data seeds, beam 50, test split). "
         r"Each beam candidate's log-probability gets a bonus $\alpha\cos(h_u, z_c)$ in a collaborative (SASRec, fit on clean or on poisoned training data) or content embedding space; "
         r"the model itself is unchanged. "
         rf"Left: all {len(allk)} cells. Right: the {len(landed)} cells where the attack landed (poisoned SH@10 at least {LANDED_PTS} points above the retrained model's, decided from the references only). "
         r"$\Delta^{\mathrm{retr}}_{\mathrm{SH}}$ is the distance to the retrained model's exposure; PGR@10 is computed from the mean exposures of the cell set; $\tau_P$ is NDCG@10 relative to the retrained model.}",
         r"\label{tab:appendix-rerank-15cells}", r"\begin{tabular}{lcccccccc}", r"\toprule",
         rf" & \multicolumn{{4}}{{c}}{{All cells ({len(allk)})}} & \multicolumn{{4}}{{c}}{{Landed cells ({len(landed)})}} \\",
         r"\cmidrule(lr){2-5} \cmidrule(lr){6-9}",
         r"Model & SH@10\,(\%) & $\Delta^{\mathrm{retr}}_{\mathrm{SH}}$ & PGR@10 & $\tau_P$\,(\%) & SH@10\,(\%) & $\Delta^{\mathrm{retr}}_{\mathrm{SH}}$ & PGR@10 & $\tau_P$\,(\%) \\",
         r"\midrule"]
    for i, (m, s, lab) in enumerate(rows):
        if i in (len(SPECS), 2 * len(SPECS)):
            L.append(r"\midrule")
        a, l = res[(m, s)]
        L.append(f"{lab} & {ft(a)} & {ft(l)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    os.makedirs("paper/revision/tables", exist_ok=True)
    open("paper/revision/tables/appendix_rerank_15cells.tex", "w").write("\n".join(L) + "\n")
    open("paper/revision/rerank_15cells.md", "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
